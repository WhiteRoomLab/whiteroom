// Command gen writes tables.go and testdata/NormalizationTest.txt.gz from the Unicode Character Database.
package main

import (
	"bytes"
	"cmp"
	"compress/gzip"
	"crypto/sha256"
	"fmt"
	"go/format"
	"io"
	"log"
	"maps"
	"net/http"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"time"
	"unicode"
)

const maxSize = 64 << 20

const (
	sBase  = 0xAC00
	sCount = 11172
)

type file struct {
	name string
	data []byte
}

type composition struct {
	first, second, composite rune
}

func main() {
	log.SetFlags(0)
	log.SetPrefix("gen: ")
	if err := run(); err != nil {
		log.Fatal(err)
	}
}

func run() error {
	client := &http.Client{Timeout: 5 * time.Minute}
	var files []file
	for _, name := range []string{"UnicodeData.txt", "DerivedNormalizationProps.txt", "NormalizationTest.txt"} {
		data, err := fetch(client, name)
		if err != nil {
			return err
		}
		files = append(files, file{name, data})
	}
	// UnicodeData.txt has no version line.
	for _, f := range files[1:] {
		want := "# " + strings.TrimSuffix(f.name, ".txt") + "-" + unicode.Version + ".txt\n"
		if !bytes.HasPrefix(f.data, []byte(want)) {
			return fmt.Errorf("%s: first line is not %q", f.name, strings.TrimSpace(want))
		}
	}
	src, err := tables(files)
	if err != nil {
		return err
	}
	var gz bytes.Buffer
	zw, err := gzip.NewWriterLevel(&gz, gzip.BestCompression)
	if err != nil {
		return err
	}
	if _, err := zw.Write(files[2].data); err != nil {
		return err
	}
	if err := zw.Close(); err != nil {
		return err
	}
	if err := os.WriteFile("tables.go", src, 0o644); err != nil {
		return err
	}
	if err := os.MkdirAll("testdata", 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join("testdata", "NormalizationTest.txt.gz"), gz.Bytes(), 0o644)
}

func fetch(c *http.Client, name string) ([]byte, error) {
	url := "https://www.unicode.org/Public/" + unicode.Version + "/ucd/" + name
	resp, err := c.Get(url)
	if err != nil {
		return nil, err
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, maxSize+1))
	if err != nil {
		return nil, fmt.Errorf("%s: %w", url, err)
	}
	if len(data) > maxSize {
		return nil, fmt.Errorf("%s: larger than %d bytes", url, maxSize)
	}
	return data, nil
}

func tables(files []file) ([]byte, error) {
	ccc, decomp, err := readUnicodeData(files[0].data)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", files[0].name, err)
	}
	fce, qc, err := readNormProps(files[1].data)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", files[1].name, err)
	}
	for r := range fce {
		if qc[r] != "N" {
			return nil, fmt.Errorf("U+%04X: Full_Composition_Exclusion but NFC_QC is not N", r)
		}
		if decomp[r] == nil {
			return nil, fmt.Errorf("U+%04X: Full_Composition_Exclusion without a decomposition", r)
		}
	}
	for r, v := range qc {
		if v == "N" && !fce[r] {
			return nil, fmt.Errorf("U+%04X: NFC_QC=N but not Full_Composition_Exclusion", r)
		}
	}
	var comps []composition
	for r, d := range decomp {
		if len(d) != 2 || fce[r] {
			continue
		}
		if ccc[d[0]] != 0 || ccc[r] != 0 {
			return nil, fmt.Errorf("U+%04X: composes from or to a non-starter", r)
		}
		comps = append(comps, composition{d[0], d[1], r})
	}
	slices.SortFunc(comps, func(x, y composition) int {
		return cmp.Or(cmp.Compare(x.first, y.first), cmp.Compare(x.second, y.second))
	})
	var full func(r rune) []rune
	full = func(r rune) []rune {
		d, ok := decomp[r]
		if !ok {
			return []rune{r}
		}
		var out []rune
		for _, x := range d {
			out = append(out, full(x)...)
		}
		return out
	}
	runes := slices.Concat(slices.Collect(maps.Keys(ccc)), slices.Collect(maps.Keys(qc)), slices.Collect(maps.Keys(decomp)))
	slices.Sort(runes)
	runes = slices.Compact(runes)
	qcName := map[string]string{"": "qcYes", "M": "qcMaybe", "N": "qcNo"}

	var b bytes.Buffer
	b.WriteString("// Code generated by \"go run ./gen\"; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "// Derived from the Unicode Character Database %s. See UNICODE-LICENSE.txt.\n", unicode.Version)
	for _, f := range files {
		fmt.Fprintf(&b, "// %s sha256:%x\n", f.name, sha256.Sum256(f.data))
	}
	fmt.Fprintf(&b, "\npackage nfc\n\nconst unicodeVersion = %q\n\nvar props = [...]prop{\n", unicode.Version)
	for _, r := range runes {
		d := ""
		if _, ok := decomp[r]; ok {
			d = string(full(r))
		}
		// Hangul syllables are decomposed and composed arithmetically, not with the tables.
		if isSyllable(r) || strings.ContainsFunc(d, isSyllable) {
			return nil, fmt.Errorf("U+%04X: Hangul syllable in the tables", r)
		}
		fmt.Fprintf(&b, "\t{0x%04X, %d, %s, %s},\n", r, ccc[r], qcName[qc[r]], strconv.QuoteToASCII(d))
	}
	b.WriteString("}\n\nvar compositions = [...]composition{\n")
	for _, c := range comps {
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X, 0x%04X},\n", c.first, c.second, c.composite)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func readUnicodeData(data []byte) (ccc map[rune]uint8, decomp map[rune][]rune, err error) {
	ccc = map[rune]uint8{}
	decomp = map[rune][]rune{}
	for line := range strings.Lines(string(data)) {
		f := strings.Split(strings.TrimSuffix(line, "\n"), ";")
		if len(f) != 15 {
			return nil, nil, fmt.Errorf("bad line %q", line)
		}
		r, err := parseRune(f[0])
		if err != nil {
			return nil, nil, err
		}
		c, err := strconv.ParseUint(f[3], 10, 8)
		if err != nil {
			return nil, nil, err
		}
		if c != 0 {
			ccc[r] = uint8(c)
		}
		// A tag such as <compat> marks a compatibility decomposition.
		if f[5] == "" || strings.HasPrefix(f[5], "<") {
			continue
		}
		for _, h := range strings.Fields(f[5]) {
			d, err := parseRune(h)
			if err != nil {
				return nil, nil, err
			}
			decomp[r] = append(decomp[r], d)
		}
	}
	return ccc, decomp, nil
}

func readNormProps(data []byte) (fce map[rune]bool, qc map[rune]string, err error) {
	fce = map[rune]bool{}
	qc = map[rune]string{}
	for line := range strings.Lines(string(data)) {
		line, _, _ = strings.Cut(line, "#")
		f := strings.Split(line, ";")
		if len(f) < 2 {
			continue
		}
		for i := range f {
			f[i] = strings.TrimSpace(f[i])
		}
		lo, hi, err := parseRange(f[0])
		if err != nil {
			return nil, nil, err
		}
		switch f[1] {
		case "Full_Composition_Exclusion":
			for r := lo; r <= hi; r++ {
				fce[r] = true
			}
		case "NFC_QC":
			if len(f) != 3 || f[2] != "N" && f[2] != "M" {
				return nil, nil, fmt.Errorf("unexpected NFC_QC line %q", line)
			}
			for r := lo; r <= hi; r++ {
				qc[r] = f[2]
			}
		}
	}
	return fce, qc, nil
}

func parseRange(s string) (lo, hi rune, err error) {
	a, b, ok := strings.Cut(s, "..")
	if !ok {
		b = a
	}
	if lo, err = parseRune(a); err != nil {
		return 0, 0, err
	}
	if hi, err = parseRune(b); err != nil {
		return 0, 0, err
	}
	return lo, hi, nil
}

func parseRune(s string) (rune, error) {
	r, err := strconv.ParseUint(s, 16, 32)
	return rune(r), err
}

func isSyllable(r rune) bool {
	return sBase <= r && r < sBase+sCount
}
